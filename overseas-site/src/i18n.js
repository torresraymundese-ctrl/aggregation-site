export function useI18n() {
  const isZh = computed(() => lang.value === 'zh')
  const t = (key) => dict[lang.value][key] || key
  const toggleLang = () => {
    lang.value = lang.value === 'en' ? 'zh' : 'en'
    writeSavedLang(lang.value)
  }

  return { lang, isZh, t, toggleLang }
}
